#!/usr/bin/env python3
"""Build the open content pack's item pictures from Flare: Empyrean Campaign.

Flare's art is CC-BY-SA 3.0 (https://github.com/flareteam/flare-game).
Writes, in the pack's layout (docs/content.md):

- System/Game/Pattern/Item0000.png + .sheet: one inventory picture per
  item, scaled from Flare's 64x64 icons to the item's size in 32-pixel
  cells,
- Character/ITEM/00000007/Pattern.png + .sheet: one ground picture per
  item, the last frame of Flare's loot animation (the item lying still).

Frames are numbered in the order of ITEMS below; content/items.txt refers
to them with icon=0,<n> and ground=7,<n>. Usage:

    python3 tools/content/import_items.py /path/to/flare-game content

Needs Pillow.
"""

import argparse
from pathlib import Path

from PIL import Image

FANTASYCORE = "mods/fantasycore"
ICON_SIZE = 64
CELL = 32

# (Flare icon number, Flare loot animation, width and height in cells)
ITEMS = [
    (97, "shortsword", 2, 2),     # 0 Short Sword
    (99, "greatsword", 2, 2),     # 1 Great Sword
    (129, "clothes", 2, 2),       # 2 Cloth Armour
    (120, "buckler", 2, 2),       # 3 Buckler
    (144, "leather_armor", 2, 2), # 4 Leather Hood
    (148, "boots", 2, 2),         # 5 Leather Boots
    (199, "ring", 1, 1),          # 6 Copper Ring
    (64, "hp_potion", 1, 1),      # 7 Healing Potion
    (65, "mp_potion", 1, 1),      # 8 Mana Potion
    (88, "coins5", 1, 1),         # 9 Gold
]

HEADER = "# Generated by tools/content/import_items.py from Flare art (CC-BY-SA 3.0).\n"


def last_loot_frame(flare, name):
    """The final frame of a loot animation and its anchor: the item at rest."""
    anim = flare / FANTASYCORE / "animations/loot" / f"{name}.txt"
    image = None
    frames = 0
    cells = {}
    for line in anim.read_text().splitlines():
        line = line.strip()
        if line.startswith("image="):
            image = line.split("=", 1)[1]
        elif line.startswith("frames="):
            frames = int(line.split("=", 1)[1])
        elif line.startswith("frame="):
            index, direction, x, y, w, h, ox, oy = map(int, line.split("=", 1)[1].split(","))
            if direction == 0:
                cells[index] = (x, y, w, h, ox, oy)
    x, y, w, h, ox, oy = cells[frames - 1]
    sheet = Image.open(flare / FANTASYCORE / image).convert("RGBA")
    return sheet.crop((x, y, x + w, y + h)), ox, oy


def write_strip(frames, folder, name):
    """Lays frames out left to right and writes <name>.png and <name>.sheet."""
    width = sum(im.width for im, _, _ in frames)
    height = max(im.height for im, _, _ in frames)
    out = Image.new("RGBA", (width, height))
    lines = [HEADER, f"image={name}.png\n"]
    x = 0
    for im, ax, ay in frames:
        out.paste(im, (x, 0))
        lines.append(f"frame={x},0,{im.width},{im.height},{ax},{ay}\n")
        x += im.width
    folder.mkdir(parents=True, exist_ok=True)
    out.save(folder / f"{name}.png", optimize=True)
    with open(folder / f"{name}.sheet", "w", newline="\n") as f:
        f.writelines(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("flare", type=Path, help="flare-game checkout")
    parser.add_argument("out", type=Path, help="content pack folder")
    args = parser.parse_args()

    icons = Image.open(args.flare / FANTASYCORE / "images/icons/icons.png").convert("RGBA")
    per_row = icons.width // ICON_SIZE
    inventory, ground = [], []
    for icon, loot, w, h in ITEMS:
        x, y = icon % per_row * ICON_SIZE, icon // per_row * ICON_SIZE
        im = icons.crop((x, y, x + ICON_SIZE, y + ICON_SIZE))
        side = min(w, h) * CELL
        im = im.resize((side, side), Image.LANCZOS)
        # Centred in the item's cells; the anchor is the top-left corner.
        cell = Image.new("RGBA", (w * CELL, h * CELL))
        cell.paste(im, ((w * CELL - side) // 2, (h * CELL - side) // 2))
        inventory.append((cell, 0, 0))
        ground.append(last_loot_frame(args.flare, loot))
    write_strip(inventory, args.out / "System/Game/Pattern", "Item0000")
    write_strip(ground, args.out / "Character/ITEM/00000007", "Pattern")
    print(f"wrote {len(ITEMS)} item pictures")


if __name__ == "__main__":
    main()
