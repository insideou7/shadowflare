#!/usr/bin/env python3
"""Write src/logic/open_area_table.inc: where each of the open content's first- and second-area
maps lies on the original's, so a saved game moves between the two (a
hero saved in the original's Remote Town stands in the same place in ours,
and back). Needs the player's own copy of the game, as first_area.py does.

    python3 tools/content/open_areas.py <game folder> <content pack>

Each map's crop is worked out as first_area.py works it out, then checked
against the pack: our map's size, and its exits moved by the crop.
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import first_area as fa  # noqa: E402

OUT = HERE.parent.parent / "src" / "logic" / "open_area_table.inc"


def check(out, number, o, x0, y0, tw, th):
    """Our map and scenario as first_area.py wrote them, against the crop."""
    text = (out / "Map" / f"{o.name}.txt").read_text()
    size = next(line for line in text.split("\n") if line.startswith("size="))
    assert size == f"size={tw},{th}", (number, size, tw, th)
    ours = (out / "Scenario" / f"{fa.our_number(number):08d}" / "scenario.txt").read_text().split("\n")
    exits = [list(map(int, line[5:].split(",")[:4])) for line in ours if line.startswith("exit=")]
    theirs = [[l - x0, t - y0, r - x0, b - y0] for l, t, r, b, target, _ in o.exits if target in fa.exit_targets(number)]
    assert exits == theirs, (number, exits, theirs)


def main():
    game, out = Path(sys.argv[1]), Path(sys.argv[2])
    if not (game / "Map").is_dir():
        game = next(p.parent for p in game.rglob("Map") if (p / "Pattern").is_dir())
    rows = []
    for number in fa.ALL:
        o = fa.Original(game, number)
        x0, y0, tw, th = fa.crop(o, fa.walkable(o))
        check(out, number, o, x0, y0, tw, th)
        w, h, cw, ch = o.chips
        rows.append(f"{{{number}, {x0}, {y0}, {tw * fa.TILE}, {th * fa.TILE}, {w * cw}, {h * ch}}},  // {o.name} {o.title}")
        print(rows[-1].strip())
    OUT.write_text("// Generated by tools/content/open_areas.py from the original's maps and the\n"
                   "// open content's (tools/content/first_area.py lays the one on the other).\n"
                   "// Original scenario, the original world point at our map's corner, our\n"
                   "// map's size in world units, the original ground's size in screen pixels.\n"
                   + "\n".join(rows) + "\n")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
