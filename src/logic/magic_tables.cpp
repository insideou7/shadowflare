MagicTables MagicTables::standard() {
    MagicTables t;
    for (int s = 0; s < kSpellCount; ++s) {
        auto& spell = t.spells[static_cast<std::size_t>(s)];
        const auto i = static_cast<std::size_t>(s);
        spell.name = kNames[s];
        spell.element = kElements[s];
        spell.castSpeed = kCastSpeed[s];
        spell.mpCost = expand<kSpellColumns>(kMpCost[i]);
        spell.power = expand<kSpellColumns>(kPower[i]);
        spell.hit = expand<kSpellColumns>(kHit[i]);
        spell.speed = expand<kSpellColumns>(kSpeed[i]);
        spell.flag21 = expand<kSpellColumns>(kFlag21[i]);
        spell.usesToLevel = expand<kMaxSpellLevel>(kUsesToLevel[i]);
        for (std::size_t c = 0; c < 4; ++c) spell.learnAt[c] = kLearnAt[c][s];
    }
    t.elementAttack = {8, 8, 8, 8, 8, 9, 9, 9, 10, 10, 10, 10, 10, 11, 11, 11, 11, 12, 12, 12, 12};   // table 7
    t.elementDefense = {8, 8, 8, 8, 8, 9, 9, 9, 10, 10, 10, 10, 10, 11, 11, 11, 11, 12, 12, 12, 12};  // table 11
    t.classWeights = {{{1, 0, 0, 0}, {0, 10, 2, 4}, {0, 2, 10, 4}, {0, 5, 2, 10}}};  // tables 100-103
    t.chantSteps = {1, 2, 3, 4, 5, 6, 7, 8};  // table 4
    for (std::size_t r = 0; r < t.berserker.size(); ++r) t.berserker[r] = expand<kSpellColumns>(kBerserkerTable[r]);
    for (std::size_t r = 0; r < t.moon.size(); ++r) t.moon[r] = expand<kSpellColumns>(kMoonTable[r]);
    for (std::size_t r = 0; r < t.stunBonus.size(); ++r) t.stunBonus[r] = {kStunBonus[r][0], kStunBonus[r][1]};
    for (std::size_t r = 0; r < t.heroStunBonus.size(); ++r) t.heroStunBonus[r] = {kHeroStunBonus[r][0], kHeroStunBonus[r][1]};
    for (const StunRow& row : kStunRows) {
        const auto chance = expand<kSpellColumns>(row.chance), length = expand<kSpellColumns>(row.length),
                   uncapped = expand<kSpellColumns>(row.uncapped);
        for (int level = 1; level <= kSpellColumns; ++level) {
            const auto c = static_cast<std::size_t>(level - 1);
            t.stun(row.element, row.spell, level) = {chance[c], length[c], uncapped[c] != 0};
        }
    }
    // Tables 204-206 are the same: 2 at level 1, one more every 5 levels, 8 at 30.
    for (std::size_t c = 0; c < kSpellColumns; ++c) {
        const int n = c == kSpellColumns - 1 ? 8 : 2 + static_cast<int>(c) / 5;
        t.counts[0][c] = t.counts[1][c] = t.counts[2][c] = n;
        t.counts[3][c] = c < 9 ? 1 : c < 20 ? 3 : 5;  // table 207
    }
    t.minePower = expand<100>({{25, 40, 10}, {16, 295, 15}, {29, 540, 20}, {30, 1130, 30}});  // table 23
    return t;
}

