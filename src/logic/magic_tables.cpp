struct Run {
    int count, first, step;
};
using Rows = std::vector<std::vector<Run>>;

template <std::size_t N>
std::array<int, N> expand(const std::vector<Run>& runs) {
    std::array<int, N> out{};
    std::size_t i = 0;
    for (const Run& r : runs) {
        for (int k = 0; k < r.count && i < N; ++k) out[i++] = r.first + k * r.step;
    }
    return out;
}

